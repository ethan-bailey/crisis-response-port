  const painter=scriptSource('SurfacePainter.cs');
  const collision=methodBody(painter,'private void OnParticleCollision(GameObject other)');
  ordered(collision,['if (!levelDecalsEnabled)','other.GetComponent<PaintableSurface>()','emitter.GetCollisionEvents(other, collisionEvents)',
    'if (wallStreaksEnabled)','component.SpawnStreak(collisionEvent.intersection, collisionEvent.velocity)',
    'delegatedPaintPixel(component, collisionEvent.intersection)'],'surface collision order changed');
  assert.match(methodBody(painter,'private bool SpawnOrUpdatePool('),/return false;/,
    'the recovered original pool stub must not be replaced with an invented implementation');
