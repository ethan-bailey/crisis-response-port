  const initialize=methodBody(surface,'private void InitializeTexture(int pixelsPerMeter)');
  ordered(initialize,['if (bloodMask != null)','new Texture2D(width, height)','bloodMask.wrapMode = TextureWrapMode.Clamp',
    'meshRenderer.materials[paintableMaterialIndex].SetTexture("_Bloodmask", bloodMask)',
    'bloodMask.SetPixels(pixels)','bloodMask.Apply()'],'generated blood-mask lifecycle changed');
  const queue=read('runtime/Engine/BrowserParticleEventQueue.cs');
