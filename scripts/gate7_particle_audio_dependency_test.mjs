function methodBody(source,signature){
  const start=source.indexOf(signature);
  assert.notEqual(start,-1,'original method missing: '+signature);
  const open=source.indexOf('{',start);
  let depth=0;
  for(let i=open;i<source.length;i++){
    if(source[i]==='{')depth++;
    else if(source[i]==='}'&&--depth===0)return source.slice(open+1,i);
  }
  assert.fail('unbalanced method body: '+signature);
}

function ordered(source,needles,message){
  let cursor=-1;
  for(const needle of needles){
    const next=source.indexOf(needle,cursor+1);
    assert.ok(next>cursor,message+': '+needle);
    cursor=next;
  }
}

function histogram(values){
  const counts={};
  for(const value of values)counts[value]=(counts[value]??0)+1;
  return counts;
}

function prefabComponent(path,classID,fileID){
  const prefab=particles.prefabs[path];
  assert.ok(prefab,'missing particle prefab: '+path);
  const record=prefab.records.find(item=>item.classID===classID&&item.fileID===fileID);
  assert.ok(record,'missing component '+classID+':'+fileID+' in '+path);
  return record;
}

test('Mission paintable surfaces preserve every serialized mode, material slot, and generated-mask owner',()=>{
  assert.equal(mission.sha256,'c43b36c415b4df14ef6223eaced686a8ddcead6c46f7504346aecb1a03c5743e');
  assert.equal(mission.records.length,7141);
  const surfaces=mission.records.filter(record=>record.classID===114&&
    record.fields?.m_Script?.guid==='c60393f2b5511f963e5c787c20bdf400');
  assert.equal(surfaces.length,67);
  assert.deepEqual(histogram(surfaces.map(record=>record.fields.mode)),{0:10,1:8,2:16,3:19,4:14});
  assert.deepEqual(histogram(surfaces.map(record=>record.fields.paintableMaterialIndex)),{0:65,2:2});
  assert.ok(surfaces.every(record=>record.fields.bloodMask.fileID==='0'),
    'blood masks are generated by PaintableSurface, not serialized texture assets');
  const slotTwo=surfaces.filter(record=>record.fields.paintableMaterialIndex===2)
    .map(record=>[record.fileID,record.fields.m_GameObject.fileID]);
  assert.deepEqual(slotTwo,[['6389','543'],['6808','1090']]);
  for(const [,gameObjectFileID] of slotTwo){
    const renderer=mission.records.find(record=>record.classID===23&&record.fields?.m_GameObject?.fileID===gameObjectFileID);
    assert.equal(renderer.fields.m_Materials[2].guid,'9c0dcb59c5309674abb715cc98a47bdb');
  }
});

